const englishToUrdu = new Map<string, string>(
  (Object.keys(translations.en) as TranslationKey[]).map((key) => [
    translations.en[key],
    translations.ur[key] ?? translations.en[key],
  ]),
);
Object.entries(literalUrdu).forEach(([english, urdu]) => englishToUrdu.set(english, urdu));

export function translateText(lang: Lang, text: string): string {
  if (lang !== 'ur' || !text) return text;
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  const core = text.trim();
  return `${leading}${englishToUrdu.get(core) ?? core}${trailing}`;
}
